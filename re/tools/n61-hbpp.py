#!/usr/bin/env python3
"""Generate a phone-side shell script that bootloads the N61 (Apple N1/Z2) touch controller
through spidev with tools/spi, in iOS order (re/MULTITOUCH.md §4).
usage: n61-hbpp.py OUT.sh [HZ] [CHUNK]   (needs re/mtfw/{C1F59-constructed,MtCl-live,PxCl-live}.bin)"""
import os, sys

D = os.path.join(os.path.dirname(__file__), '..', 'mtfw')
rd = lambda n: open(os.path.join(D, n), 'rb').read()

def sw32(v):
    return bytes([(v >> 8) & 0xff, v & 0xff, (v >> 24) & 0xff, (v >> 16) & 0xff])

def be16(v):
    return bytes([(v >> 8) & 0xff, v & 0xff])

def swab16(b):
    b = b + b'\0' * (-len(b) % 4)
    return bytes(x for i in range(0, len(b), 2) for x in (b[i + 1], b[i]))

def data_pkt(addr, wire):
    """DATA packet; wire = payload already in on-wire (pair-swapped) byte order."""
    assert len(wire) % 4 == 0
    hdr = be16(len(wire) // 4) + sw32(addr)
    return b'\x18\xe1\x30\x01' + hdr + be16(sum(hdr)) + wire + sw32(sum(wire))

def cmd(op, body):
    return be16(op) + body + be16(sum(body))

def mem_write(addr, val, mask=0xffffffff):
    return cmd(0x1e33, sw32(addr) + sw32(mask) + sw32(val))

def mem_read(addr):
    return cmd(0x1c73, sw32(addr))

def execute(addr):
    return cmd(0x1d53, sw32(addr) + sw32(1))

fw = rd('C1F59-constructed.bin')
# self-check: rebuilding Apple's preconstructed packet must give identical bytes
assert data_pkt(0, fw[12:-4]) == fw, 'packet builder does not match the iOS blob'

out = sys.argv[1]
hz = int(sys.argv[2]) if len(sys.argv) > 2 else 4000000
chunk = int(sys.argv[3], 0) if len(sys.argv) > 3 else 0x3f0
S = f'/tmp/spi /dev/spidev0.0 {hz} 0'
ACK = '1aa1'
L = ['#!/bin/sh', '# generated by re/tools/n61-hbpp.py — N61 touch bootload over spidev']

def pkt(tag, p, ack=ACK):
    L.append(f'echo "== {tag}"; {S} {p.hex()} c {ack} | tail -1')

def blob(tag, base, raw):
    wire = swab16(raw)
    for off in range(0, len(wire), chunk):
        pkt(f'{tag} @{base + off:#x}', data_pkt(base + off, wire[off:off + chunk]))

blob('PxCl', 0x10009600, rd('PxCl-live.bin'))
blob('MtCl', 0x10009000, rd('MtCl-live.bin'))
wire = fw[12:-4]
for off in range(0, len(wire), chunk):
    pkt(f'fw @{off:#x}', data_pkt(off, wire[off:off + chunk]))
LACK = '1aa118e118e118e1'
pkt('read version 0x10008ffc', mem_read(0x10008ffc), LACK)
for a, v in ((0x10003060, 0x17d3), (0x1000305c, 2), (0x10003058, 6), (0x10003000, 3), (0x10003518, 1)):
    pkt(f'write {a:#x}={v:#x}', mem_write(a, v))
pkt('read SPI_APU_EN 0x10003800', mem_read(0x10003800), LACK)
L.append(f'echo "== calibrate"; {S} 1f01; sleep 0.07; {S} {ACK}')
L.append(f'echo "== execute"; {S} {execute(0x10003400).hex()}; sleep 0.05')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{out}: {len(L) - 2} steps, chunk {chunk:#x}, {hz} Hz')
